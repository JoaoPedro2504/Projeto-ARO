    @wraps(view)
    # Aqui começa uma função: o código dela só roda quando essa função é chamada.
    def protegido(*args, **kwargs):
        # Aqui o código confere uma condição; se for verdadeira, entra nesse bloco.
        if 'id_usuario' not in session:
            # Guarda uma mensagem para aparecer na página, como aviso de erro ou sucesso.
            flash('Você precisa estar logado.', 'error')
            # Manda o navegador abrir outro endereço depois dessa ação.
            return redirect(url_for('login'))
        # Aqui um valor está sendo guardado numa variável ou uma informação está sendo configurada.
        con = conectar()
        # Aqui um valor está sendo guardado numa variável ou uma informação está sendo configurada.
        cur = con.cursor()
        # Tenta executar esse pedaço do código e fica pronto para tratar algum erro.
        try:
            # Envia um comando SQL para o banco Firebird; os ? recebem os valores sem montar SQL na mão.
            cur.execute('SELECT ATIVO, BLOQUEADO FROM USUARIO WHERE ID_USUARIO = ?', (session['id_usuario'],))
            # Aqui um valor está sendo guardado numa variável ou uma informação está sendo configurada.
            situacao = cur.fetchone()
        # Esse bloco roda no final, mesmo se deu erro, para fechar recursos.
        finally:
            # Fecha essa conexão ou cursor para não deixar recurso aberto.
            cur.close()
            # Fecha essa conexão ou cursor para não deixar recurso aberto.
            con.close()
        # Aqui o código confere uma condição; se for verdadeira, entra nesse bloco.
        if not situacao or not situacao[0] or situacao[1]:
            # Usa a sessão para lembrar quem entrou ou para sair da conta.
            session.clear()
            # Guarda uma mensagem para aparecer na página, como aviso de erro ou sucesso.
            flash('Conta inativa ou bloqueada. Entre em contato com o administrador.', 'error')
            # Manda o navegador abrir outro endereço depois dessa ação.
            return redirect(url_for('login'))
        # Devolve um resultado e termina a execução dessa função nesse ponto.
        return view(*args, **kwargs)
    # Devolve um resultado e termina a execução dessa função nesse ponto.
    return protegido


