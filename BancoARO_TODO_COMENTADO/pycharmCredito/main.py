def senha_forte(senha):
    # Validação artesanal, usando funções nativas do Python.
    # Devolve um resultado e termina a execução dessa função nesse ponto.
    return (len(senha) >= 8 and any(c.isupper() for c in senha)
            # Essa instrução faz parte da lógica que está sendo executada nesse bloco.
            and any(c.islower() for c in senha) and any(c.isdigit() for c in senha))


