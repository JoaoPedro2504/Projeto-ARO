def valor_monetario(texto):
    # Aqui um valor está sendo guardado numa variável ou uma informação está sendo configurada.
    texto = (texto or '').strip().replace('R$', '').replace(' ', '')
    # Aqui o código confere uma condição; se for verdadeira, entra nesse bloco.
    if ',' in texto:
        # Aqui um valor está sendo guardado numa variável ou uma informação está sendo configurada.
        texto = texto.replace('.', '').replace(',', '.')
    # Tenta executar esse pedaço do código e fica pronto para tratar algum erro.
    try:
        # Aqui um valor está sendo guardado numa variável ou uma informação está sendo configurada.
        valor = Decimal(texto)
        # Aqui o código confere uma condição; se for verdadeira, entra nesse bloco.
        if not valor.is_finite() or valor < 0:
            # Interrompe esse caminho porque foi encontrada uma situação inválida.
            raise ValueError()
        # Devolve um resultado e termina a execução dessa função nesse ponto.
        return valor
    # Se acontecer esse tipo de erro, cai nesse bloco em vez de parar o site.
    except (InvalidOperation, ValueError):
        # Interrompe esse caminho porque foi encontrada uma situação inválida.
        raise ValueError('Informe valores válidos para renda e despesas.')


