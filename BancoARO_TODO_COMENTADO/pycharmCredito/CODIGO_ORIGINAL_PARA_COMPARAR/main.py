@app.route('/cadastro', methods=['GET', 'POST'])
def cadastro():
    if request.method == 'GET':
        return render_template('cadastro.html')
    nome = request.form.get('nome', '').strip()
    email = request.form.get('email', '').strip().lower()
    senha = request.form.get('senha', '')
    if not nome or not email or not senha:
        flash('Preencha nome, e-mail e senha.', 'error')
        return redirect(url_for('cadastro'))
    if not senha_forte(senha):
        flash('Use pelo menos 8 caracteres, com maiúscula, minúscula e número.', 'error')
        return redirect(url_for('cadastro'))
    try:
        receita = valor_monetario(request.form.get('renda'))
        despesa = valor_monetario(request.form.get('despesas'))
    except ValueError as e:
        flash(str(e), 'error')
        return redirect(url_for('cadastro'))
    con = conectar()
    cursor = con.cursor()
    try:
        cursor.execute('SELECT 1 FROM USUARIO WHERE LOWER(EMAIL) = ?', (email,))
        if cursor.fetchone():
            flash('Este e-mail já foi cadastrado.', 'error')
            return redirect(url_for('cadastro'))
        hash_senha = bcrypt.generate_password_hash(senha).decode('utf-8')
        cursor.execute('''INSERT INTO USUARIO
            (NOME, EMAIL, SENHA, RECEITA_MENSAL, DESPESA_MENSAL, TIPO_USUARIO)
            VALUES (?, ?, ?, ?, ?, ?)''', (nome, email, hash_senha, receita, despesa, 1))
        con.commit()
        flash('Cadastro realizado! Entre na sua conta.', 'success')
        return redirect(url_for('login'))
    except Exception:
        con.rollback()
        app.logger.exception('Falha no cadastro')
        flash('Não foi possível concluir o cadastro.', 'error')
        return redirect(url_for('cadastro'))
    finally:
        cursor.close()
        con.close()


@app.route('/login', methods=['GET', 'POST'])
def login():
    if request.method == 'GET':
        return render_template('login.html')
    email = request.form.get('email', '').strip().lower()
    senha = request.form.get('senha', '')
    con = conectar()
    cursor = con.cursor()
    try:
        cursor.execute('''SELECT ID_USUARIO, NOME, SENHA, ATIVO, TENTATIVAS_LOGIN, BLOQUEADO
                          FROM USUARIO WHERE LOWER(EMAIL) = ?''', (email,))
        usuario = cursor.fetchone()
        if not usuario:
            flash('E-mail ou senha incorretos.', 'error')
            return redirect(url_for('login'))
        id_usuario, nome, senha_hash, ativo, tentativas, bloqueado = usuario
        if not ativo:
            flash('Usuário inativo. Entre em contato com o administrador.', 'error')
            return redirect(url_for('login'))
        if bloqueado or tentativas >= 3:
            flash('Usuário bloqueado após 3 tentativas. Entre em contato com o administrador.', 'error')
            return redirect(url_for('login'))
        if not bcrypt.check_password_hash(senha_hash, senha):
            tentativas = (tentativas or 0) + 1
            cursor.execute('''UPDATE USUARIO SET TENTATIVAS_LOGIN = ?, BLOQUEADO = ?
                              WHERE ID_USUARIO = ?''', (tentativas, 1 if tentativas >= 3 else 0, id_usuario))
            con.commit()
            if tentativas >= 3:
                flash('Usuário bloqueado após 3 tentativas incorretas.', 'error')
            else:
                flash(f'E-mail ou senha incorretos. Tentativa {tentativas} de 3.', 'error')
            return redirect(url_for('login'))
        cursor.execute('UPDATE USUARIO SET TENTATIVAS_LOGIN = 0 WHERE ID_USUARIO = ?', (id_usuario,))
        con.commit()
        session.clear()
        session['id_usuario'] = id_usuario
        session['nome_usuario'] = nome
        flash('Login realizado com sucesso!', 'success')
        return redirect(url_for('inicio'))
    except Exception:
        con.rollback()
        app.logger.exception('Falha no login')
        flash('Não foi possível entrar no momento.', 'error')
        return redirect(url_for('login'))
    finally:
        cursor.close()
        con.close()


