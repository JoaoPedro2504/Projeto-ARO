@app.route('/editar_usuario', methods=['GET', 'POST'])
@autenticado
def editar_usuario():
    # Edita o usuário autenticado sem modificar a chave primária.
    con = conectar()
    cursor = con.cursor()
    try:
        cursor.execute('''SELECT NOME, EMAIL, RECEITA_MENSAL, DESPESA_MENSAL, SENHA
                          FROM USUARIO WHERE ID_USUARIO = ?''', (session['id_usuario'],))
        usuario = cursor.fetchone()
        if not usuario:
            session.clear()
            flash('Usuário não encontrado.', 'error')
            return redirect(url_for('login'))
        if request.method == 'GET':
            return render_template('editar_usuario.html', usuario=usuario)
        nome = request.form.get('nome', '').strip()
        email = request.form.get('email', '').strip().lower()
        senha = request.form.get('senha', '')
        if not nome or not email:
            flash('Nome e e-mail são obrigatórios.', 'error')
            return redirect(url_for('editar_usuario'))
        if senha and not senha_forte(senha):
            flash('A nova senha deve ter 8 caracteres, maiúscula, minúscula e número.', 'error')
            return redirect(url_for('editar_usuario'))
        receita = valor_monetario(request.form.get('renda'))
        despesa = valor_monetario(request.form.get('despesas'))
        cursor.execute('SELECT 1 FROM USUARIO WHERE LOWER(EMAIL) = ? AND ID_USUARIO <> ?',
                       (email, session['id_usuario']))
        if cursor.fetchone():
            flash('Este e-mail já está em uso.', 'error')
            return redirect(url_for('editar_usuario'))
        if senha:
            if senha_ja_utilizada(cursor, session['id_usuario'], senha, usuario[4]):
                flash('A nova senha não pode ser igual à atual ou a uma das 3 anteriores.', 'error')
                return redirect(url_for('editar_usuario'))
            hash_senha = bcrypt.generate_password_hash(senha).decode('utf-8')
            cursor.execute('''INSERT INTO HISTORICO_SENHA (ID_USUARIO, SENHA_HASH)
                              VALUES (?, ?)''', (session['id_usuario'], usuario[4]))
            cursor.execute('''UPDATE USUARIO SET NOME=?, EMAIL=?, SENHA=?, RECEITA_MENSAL=?, DESPESA_MENSAL=?
                              WHERE ID_USUARIO=?''', (nome, email, hash_senha, receita, despesa, session['id_usuario']))
        else:
            cursor.execute('''UPDATE USUARIO SET NOME=?, EMAIL=?, RECEITA_MENSAL=?, DESPESA_MENSAL=?
                              WHERE ID_USUARIO=?''', (nome, email, receita, despesa, session['id_usuario']))
        if senha:
            cursor.execute('''DELETE FROM HISTORICO_SENHA WHERE ID_USUARIO = ?
                              AND ID_HISTORICO NOT IN (
                                SELECT FIRST 3 ID_HISTORICO FROM HISTORICO_SENHA
                                WHERE ID_USUARIO = ? ORDER BY ID_HISTORICO DESC
                              )''', (session['id_usuario'], session['id_usuario']))
        con.commit()
        session['nome_usuario'] = nome
        flash('Dados atualizados.', 'success')
        return redirect(url_for('inicio'))
    except ValueError as e:
        flash(str(e), 'error')
        return redirect(url_for('editar_usuario'))
    except Exception:
        con.rollback()
        app.logger.exception('Falha na edição')
        flash('Não foi possível atualizar os dados.', 'error')
        return redirect(url_for('inicio'))
    finally:
        cursor.close()
        con.close()


