# Autenticação e cadastro do Banco ARO (Flask + Firebird).
import os
from functools import wraps
from pathlib import Path
from decimal import Decimal, InvalidOperation

import fdb
from flask import Flask, render_template, request, flash, redirect, url_for, session
from flask_bcrypt import Bcrypt

BASE = Path(__file__).resolve().parent
app = Flask(__name__, template_folder=str(BASE / 'Templates'), static_folder=str(BASE / 'Static'), static_url_path='/static')
app.config['SECRET_KEY'] = os.environ.get('ARO_SECRET_KEY', 'CHAVE-LOCAL-TROQUE-ANTES-DE-PUBLICAR')
bcrypt = Bcrypt(app)
DB_PATH = Path(os.environ.get('ARO_DB_PATH', str(BASE.parent / 'BANCO.FDB')))


def conectar():
    return fdb.connect(host=os.environ.get('ARO_DB_HOST', 'localhost'),
                       database=str(DB_PATH), user=os.environ.get('ARO_DB_USER', 'sysdba'),
                       password=os.environ.get('ARO_DB_PASSWORD', 'masterkey'), charset='UTF8')



def preparar_seguranca():
    # Migração idempotente: executar com permissão DDL.
    con = conectar()
    cur = con.cursor()
    try:
        cur.execute("SELECT TRIM(RDB$FIELD_NAME) FROM RDB$RELATION_FIELDS WHERE RDB$RELATION_NAME = 'USUARIO'")
        campos = {r[0].upper() for r in cur.fetchall()}
        for nome, tipo in [('ATIVO', 'SMALLINT DEFAULT 1 NOT NULL'),
                           ('TENTATIVAS_LOGIN', 'SMALLINT DEFAULT 0 NOT NULL'),
                           ('BLOQUEADO', 'SMALLINT DEFAULT 0 NOT NULL')]:
            if nome not in campos:
                cur.execute(f'ALTER TABLE USUARIO ADD {nome} {tipo}')
                con.commit()
        cur.execute("SELECT COUNT(*) FROM RDB$RELATIONS WHERE RDB$RELATION_NAME = 'HISTORICO_SENHA'")
        if cur.fetchone()[0] == 0:
            cur.execute('''CREATE TABLE HISTORICO_SENHA (
                ID_HISTORICO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ID_USUARIO INTEGER NOT NULL,
                SENHA_HASH VARCHAR(255) NOT NULL,
                CRIADO_EM TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                CONSTRAINT FK_HIST_SENHA_USUARIO FOREIGN KEY (ID_USUARIO)
                    REFERENCES USUARIO(ID_USUARIO) ON DELETE CASCADE
            )''')
            con.commit()
        # As senhas atuais são verificadas diretamente na tabela USUARIO.
        # O histórico só armazena senhas anteriores a partir da primeira troca.
    except Exception:
        con.rollback()
        raise
    finally:
        cur.close()
        con.close()


def senha_ja_utilizada(cursor, id_usuario, nova_senha, hash_atual):
    if bcrypt.check_password_hash(hash_atual, nova_senha):
        return True
    cursor.execute('''SELECT FIRST 3 SENHA_HASH FROM HISTORICO_SENHA
                      WHERE ID_USUARIO = ? ORDER BY ID_HISTORICO DESC''', (id_usuario,))
    return any(bcrypt.check_password_hash(item[0], nova_senha) for item in cursor.fetchall())


def senha_forte(senha):
    # Validação artesanal, usando funções nativas do Python.
    return (len(senha) >= 8 and any(c.isupper() for c in senha)
            and any(c.islower() for c in senha) and any(c.isdigit() for c in senha))


def valor_monetario(texto):
    texto = (texto or '').strip().replace('R$', '').replace(' ', '')
    if ',' in texto:
        texto = texto.replace('.', '').replace(',', '.')
    try:
        valor = Decimal(texto)
        if not valor.is_finite() or valor < 0:
            raise ValueError()
        return valor
    except (InvalidOperation, ValueError):
        raise ValueError('Informe valores válidos para renda e despesas.')


def autenticado(view):
    @wraps(view)
    def protegido(*args, **kwargs):
        if 'id_usuario' not in session:
            flash('Você precisa estar logado.', 'error')
            return redirect(url_for('login'))
        con = conectar()
        cur = con.cursor()
        try:
            cur.execute('SELECT ATIVO, BLOQUEADO FROM USUARIO WHERE ID_USUARIO = ?', (session['id_usuario'],))
            situacao = cur.fetchone()
        finally:
            cur.close()
            con.close()
        if not situacao or not situacao[0] or situacao[1]:
            session.clear()
            flash('Conta inativa ou bloqueada. Entre em contato com o administrador.', 'error')
            return redirect(url_for('login'))
        return view(*args, **kwargs)
    return protegido


